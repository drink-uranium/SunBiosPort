#!/usr/bin/env python3
"""Convert OpenBoot's gallant.fth font and logodata.fth Sun logo (from
https://github.com/openbios/openboot, obp/pkg/termemu and obp/pkg/sunlogo)
into C arrays for the x86 port. The bitmaps are used unmodified."""
import re, sys

def font(path):
    t = open(path).read()
    longs = [int(x, 16) for x in re.findall(r'\b([0-9a-fA-F]{8}) l,', t)]
    raw = b''.join(v.to_bytes(4, 'big') for v in longs)
    assert raw[:4] == b'font'
    w, h, adv, minc, nglyph = (int.from_bytes(raw[4 + 4*i:8 + 4*i], 'big') for i in range(5))
    bits = raw[24:]
    out = ['/* Generated by tools/fth2c.py from third_party/openboot/gallant.fth.',
           ' * Sun Gallant 12x22 console font, Copyright 1990-1994 Sun Microsystems, Inc.',
           ' * See third_party/openboot/LICENSE.sun for the redistribution terms. */',
           '#include "font.h"',
           'const struct obp_font gallant_font = {',
           f'    .width = {w}, .height = {h}, .advance = {adv},',
           f'    .min_char = {minc}, .nglyphs = {nglyph},',
           '    .bits = {']
    for i in range(0, len(bits), 16):
        out.append('        ' + ', '.join(f'0x{b:02x}' for b in bits[i:i+16]) + ',')
    out += ['    },', '};', '']
    return '\n'.join(out), len(bits)

def logo(path):
    t = open(path).read()
    t = t[t.index('label sun-logo'):]
    words = [int(x, 16) for x in re.findall(r'\b([0-9a-fA-F]{4}) w,', t)]
    assert len(words) == 64 * 4
    raw = b''.join(v.to_bytes(2, 'big') for v in words)
    out = ['/* Generated by tools/fth2c.py from third_party/openboot/logodata.fth.',
           ' * 64x64x1 Sun logo, Copyright 1990-1994 Sun Microsystems, Inc.',
           ' * See third_party/openboot/LICENSE.sun for the redistribution terms. */',
           '#include "font.h"',
           'const unsigned char sun_logo[64 * 8] = {']
    for i in range(0, len(raw), 8):
        out.append('    ' + ', '.join(f'0x{b:02x}' for b in raw[i:i+8]) + ',')
    out += ['};', '']
    return '\n'.join(out)

if __name__ == '__main__':
    src, n = font(sys.argv[1])
    open(sys.argv[3], 'w').write(src.replace('.bits = {', '.bits = {', 1))
    open(sys.argv[4], 'w').write(logo(sys.argv[2]))
    print('font bytes', n)
